/** Where the files live, relative to index.html. */
export const IMAGE_DIR = 'img/exercises/';

/**
 * The picture for an exercise, or null if there isn't one.
 *
 * ⚠️ Takes the exercise OBJECT, not a name. Two exercises in this library share
 * the name "Cable Kickback" and only the id separates them, so a name-keyed
 * lookup would eventually show a triceps picture over a glute exercise.
 */
export function imageFor(exercise) {
  if (!exercise || !exercise.id) return null;
  const ext = MANIFEST[exercise.id];
  return ext ? `${IMAGE_DIR}${exercise.id}.${ext}` : null;
}

/** Same, for a bare id — used where a session row carries the id and no object. */
export function imageForId(id) {
  const ext = id ? MANIFEST[id] : null;
  return ext ? `${IMAGE_DIR}${id}.${ext}` : null;
}

/** Is there any art at all? Screens use this to stay silent about the feature. */
export function hasImages() {
  return Object.keys(MANIFEST).length > 0;
}

/** Every file the manifest claims, for the service worker and the tests. */
export function manifestPaths() {
  return Object.entries(MANIFEST).map(([id, ext]) => `${IMAGE_DIR}${id}.${ext}`);
}
